import { test, expect } from '@playwright/test';
test('original 2D cave: movement, flight, shooting, equipment and resume', async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: '燐の底', exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath('01-title.png') });
  await page.getByRole('button', { name: '新しい旅を始める', exact: true }).click();
  const canvas = page.locator('#cave');
  await expect(canvas).toHaveAttribute('data-phase', 'playing');
  await expect(page.locator('#overlay')).toBeHidden();
  await expect.poll(async () => Number(await canvas.getAttribute('data-tick'))).toBeGreaterThan(8);
  const startX = Number(await canvas.getAttribute('data-player-x'));
  await page.keyboard.down('KeyD');
  await expect(canvas).toHaveAttribute('data-input-move', '1');
  await expect.poll(async () => Number(await canvas.getAttribute('data-player-x'))).toBeGreaterThan(startX + 10);
  await page.keyboard.up('KeyD');
  await page.locator('[data-wand="1"]').click();
  await page.keyboard.down('KeyD'); await page.waitForTimeout(150); await page.keyboard.up('KeyD');
  await page.locator('[data-wand="0"]').click();
  await page.keyboard.down('Space');
  await expect.poll(async () => Number(await canvas.getAttribute('data-fuel'))).toBeLessThan(90);
  await page.keyboard.up('Space');
  const box = await canvas.boundingBox(); if (!box) throw new Error('Canvas missing');
  await page.mouse.move(box.width * .7, box.height * .45); await page.mouse.down();
  await expect.poll(async () => Number(await canvas.getAttribute('data-projectiles'))).toBeGreaterThan(0);
  await page.mouse.up();
  await page.locator('#menu-button').click();
  await expect(page.getByRole('heading', { name: '旅の装備' })).toBeVisible();
  await expect(page.locator('.spell-slots select').first()).toBeDisabled();
  const pausedX = await canvas.getAttribute('data-player-x');
  await page.waitForTimeout(150); expect(await canvas.getAttribute('data-player-x')).toBe(pausedX);
  await page.screenshot({ path: info.outputPath('02-equipment.png') });
  await page.keyboard.press('Escape'); await expect(page.locator('#overlay')).toBeHidden();
  await page.setViewportSize({ width: 844, height: 390 });
  await expect(canvas).toHaveJSProperty('clientWidth', 844);
  await page.screenshot({ path: info.outputPath('03-cave-landscape.png') });
  await page.locator('#menu-button').click();
  await page.getByRole('button', { name: '保存してタイトルへ' }).click();
  await page.reload(); await page.getByRole('button', { name: '旅を続ける', exact: true }).click();
  await expect(canvas).toHaveAttribute('data-phase', 'playing');
  expect(Number(await canvas.getAttribute('data-player-x'))).toBeGreaterThan(startX + 8);
  expect(errors).toEqual([]);
});
test('trusted multi-touch movement, aim, flight and cancellation', async ({ page, context }, info) => {
  test.skip(info.project.name !== 'android-chromium', 'Touch profile only');
  await page.setViewportSize({ width: 844, height: 390 });
  await page.goto('/'); await page.getByRole('button', { name: '新しい旅を始める', exact: true }).click();
  const cdp = await context.newCDPSession(page);
  const move = await page.locator('.move-pad').boundingBox(), aim = await page.locator('.aim-pad').boundingBox(), fly = await page.locator('.fly-button').boundingBox();
  if (!move || !aim || !fly) throw new Error('Touch controls missing');
  const points = [{ x: move.x + move.width * .8, y: move.y + move.height / 2, id: 1 }, { x: aim.x + aim.width * .8, y: aim.y + aim.height * .4, id: 2 }, { x: fly.x + fly.width / 2, y: fly.y + fly.height / 2, id: 3 }];
  const canvas = page.locator('#cave'), x = Number(await canvas.getAttribute('data-player-x'));
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: points });
  await expect.poll(async () => Number(await canvas.getAttribute('data-player-x'))).toBeGreaterThan(x + 8);
  await expect.poll(async () => Number(await canvas.getAttribute('data-fuel'))).toBeLessThan(95);
  await expect.poll(async () => Number(await canvas.getAttribute('data-projectiles'))).toBeGreaterThan(0);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] });
  await page.waitForTimeout(450); const stop = Number(await canvas.getAttribute('data-player-x'));
  await page.waitForTimeout(400); expect(Math.abs(Number(await canvas.getAttribute('data-player-x')) - stop)).toBeLessThan(1);
  await page.screenshot({ path: info.outputPath('04-trusted-touch.png') });
  await page.setViewportSize({ width: 393, height: 851 });
  for (const selector of ['.move-pad','.aim-pad','.fly-button','.spray-button','#menu-button']) {
    const rect = await page.locator(selector).boundingBox(); expect(rect).not.toBeNull(); expect(rect!.width).toBeGreaterThanOrEqual(48); expect(rect!.height).toBeGreaterThanOrEqual(48); expect(rect!.x).toBeGreaterThanOrEqual(0); expect(rect!.x + rect!.width).toBeLessThanOrEqual(393);
  }
  await page.screenshot({ path: info.outputPath('05-cave-portrait.png') });
});
